const KNOWN_PREFIX: Array<[string, string]> = Object.entries(PROGRAMS)

export function programLabel(programId: string): string {
  if (PROGRAMS[programId]) return PROGRAMS[programId]
  for (const [id, name] of KNOWN_PREFIX) {
    if (id === programId) return name
  }
  return 'Unknown program'
}

export function isSwapProgram(programId: string): boolean {
  const name = (PROGRAMS[programId] ?? '').toLowerCase()
  if (
    name.includes('jupiter') ||
    name.includes('raydium') ||
    name.includes('orca') ||
    name.includes('phoenix') ||
    name.includes('openbook') ||
    name.includes('serum') ||
    name.includes('pumpswap') ||
    name.includes('pump.fun') ||
    name.includes('dflow')
  ) {
    return true
  }
  return false
}

export function isTokenProgram(programId: string): boolean {
  return programId === TOKEN || programId === TOKEN_2022 || programId === ATA
}
